"""Embed the m365-usage-sql queries into the M365 Usage Analytics template's M365Table function.

    python scripts/patch_m365_pbit.py

Run after scripts/gen_m365_usage_sql.py. The M365 ingester writes m365_usage_rollup (non-AI operations) plus
connected_ai_app_interactions and ai_app_interactions; Copilot interactions come from the Copilot audit ingester's
Copilot_Interactions_Parsed. Rollup, SessionStats, UserStats, SessionCohort and EntraUsers are computed from those
by these queries on the SQL analytics endpoint at refresh.
Rewrites the .pbit's M365Table function in place (idempotent).
"""
from __future__ import annotations

import json
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PBIT = ROOT / '08-report-templates' / 'M365 Usage Analytics - Fabric.pbit'
SQL_DIR = ROOT / '08-report-templates' / 'm365-usage-sql'
DERIVED = {'m365_usage_rollup': 'rollup', 'm365_usage_sessionstats': 'sessionstats',
           'm365_usage_userstats': 'userstats', 'm365_usage_sessioncohort': 'sessioncohort',
           'm365_usage_entrausers': 'entrausers'}
USAGE_TABLES = ['m365_usage_rollup', 'copilot_interactions_parsed', 'connected_ai_app_interactions',
                'ai_app_interactions']
NEEDS = {t: USAGE_TABLES for t in DERIVED} | {'m365_usage_entrausers': ['copilot_org_data', 'copilot_licensed_users']}


def m_list(xs) -> str:
    return '{' + ', '.join(f'"{x}"' for x in xs) + '}'


def m_text(s: str) -> str:
    if '#(' in s:
        sys.exit('SQL contains "#(", which M would read as an escape')
    return '"' + s.replace('"', '""') + '"'


def m365table() -> str:
    queries = ',\n'.join(f'\t\t\t{t} = {m_text((SQL_DIR / f"{f}.sql").read_text(encoding="utf-8").strip())}'
                         for t, f in DERIVED.items())
    needs = ',\n'.join(f'\t\t\t{t} = {m_list(n)}' for t, n in NEEDS.items())
    return f'''(tableName as text) as table =>
	let
		Db = Sql.Database(#"Fabric SQL Endpoint", #"Lakehouse Name"),
		// The report tables are computed on the SQL endpoint from the lake's M365 usage and Copilot tables.
		// Generated by scripts/patch_m365_pbit.py from 08-report-templates/m365-usage-sql.
		Derived = [
{queries}
		],
		Needs = [
{needs}
		],
		Key = Text.Lower(tableName),
		IsDerived = Record.HasFields(Derived, Key),
		Names = try List.Transform(Table.SelectRows(Db, each [Schema] = "dbo")[Item], Text.Lower) otherwise {{}},
		Missing = List.Difference(if IsDerived then Record.Field(Needs, Key) else {{Key}}, Names),
		Data = if List.IsEmpty(Names)
		       then error "Connected to '" & #"Fabric SQL Endpoint" & "' but no dbo tables are visible in database '" & #"Lakehouse Name" & "'. Check the Lakehouse Name parameter and that your account can access the workspace."
		       else if not List.IsEmpty(Missing)
		       then error "Table(s) " & Text.Combine(Missing, ", ") & " not in database '" & #"Lakehouse Name" & "'. Run Copilot_Audit_Log_Direct_Ingester and M365_Usage_Audit_Ingester, wait 1-2 minutes for the SQL endpoint to sync, then Refresh."
		       else if IsDerived then Value.NativeQuery(Db, Record.Field(Derived, Key), null, [EnableFolding = false])
		       else Table.SelectRows(Db, each [Schema] = "dbo" and Text.Lower([Item]) = Key){{0}}[Data],
		// The report queries were written for CSV files: every value is text and the first row
		// holds the headers. Reproduce that shape so every downstream step runs unchanged.
		AsText = Table.TransformColumns(Data,
		    List.Transform(Table.ColumnNames(Data), (c) => {{c, each if _ = null then "" else Text.From(_, "en-US"), type text}})),
		CsvShape = Table.DemoteHeaders(AsText)
	in
		CsvShape'''


def main():
    with zipfile.ZipFile(PBIT) as z:
        items = [(i, z.read(i.filename)) for i in z.infolist()]
    out = []
    for info, data in items:
        if info.filename == 'SecurityBindings':
            continue
        if info.filename == 'DataModelSchema':
            text = data.decode('utf-16-le').lstrip('\ufeff')
            model = json.loads(text)
            exprs = [e for e in model['model']['expressions'] if e['name'] == 'M365Table']
            if len(exprs) != 1:
                sys.exit('M365Table expression not found')
            exprs[0]['expression'] = m365table().split('\n')
            data = json.dumps(model, ensure_ascii=False, indent=2).encode('utf-16-le')
            json.loads(data.decode('utf-16-le'))
        out.append((info, data))
    tmp = PBIT.with_suffix('.tmp')
    with zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED) as z:
        for info, data in out:
            z.writestr(info, data, compress_type=info.compress_type)
    tmp.replace(PBIT)
    print(f'patched {PBIT.name}')


if __name__ == '__main__':
    main()
