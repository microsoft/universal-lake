"""Generate the T-SQL that the M365 Usage Analytics template runs on the Fabric SQL endpoint.

Writes 08-report-templates/m365-usage-sql/{userstats,sessioncohort,entrausers}.sql. These replace the
retired M365_Usage_Gold notebook: the lake keeps only the generic daily rollups
(dbo.m365_usage_rollup, dbo.m365_usage_sessionstats) and the template derives its report-specific
tables (tiers, percentiles, ranks, cohorts) at refresh time. The rules mirror write_userstats_files in
the original PAX processor; scripts/test_m365_usage_sql.py checks parity against it.

The SQL sticks to a subset that runs on both the Fabric endpoint and Spark SQL (for the parity test):
no IIF/APPLY/string '+', explicit FLOAT casts, and dates handled only via DATEADD/DATEDIFF on DATE.

Run: python scripts/gen_m365_usage_sql.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / '08-report-templates' / 'm365-usage-sql'

WORD_EXTS = ['docx', 'doc', 'dotx']
EXCEL_EXTS = ['xlsx', 'xls', 'xlsm', 'csv']
PPT_EXTS = ['pptx', 'ppt', 'ppsx']
FILE_OPS = ['FileAccessed', 'FileModified', 'FileDownloaded', 'FileUploaded']
OUTLOOK_OPS = ['Send', 'MailItemsAccessed', 'MailboxLogin']
TEAMS_OPS = ['MessageSent', 'MessageRead', 'ChatCreated', 'MeetingParticipantDetail', 'TeamsSessionStarted']
COPILOT_OPS = ['CopilotInteraction', 'AIAppInteraction']
DAX_FILE_OPS = FILE_OPS + ['FilePreviewed']
DAX_OUTLOOK_OPS = ['Send', 'MailItemsAccessed']
DAX_TEAMS_OPS = ['MessageSent', 'MessageRead', 'MessagesListed', 'ChatRetrieved', 'MeetingParticipantDetail',
                 'MeetingStarted', 'MeetingEnded', 'TeamsSessionStarted']
COPILOT_SKU = '639dec6b-bb19-468b-871c-c5c441c4b0cb'
WINDOWS = ['L30', 'L60', 'Full']
RAW_APPS = ['Teams', 'Outlook', 'Word', 'Excel', 'PowerPoint', 'CopilotChat']
RANK_APPS = ['Teams', 'Outlook', 'Word', 'Excel', 'PowerPoint', 'M365AllApps']


def _in(values):
    return '(' + ', '.join("'" + v + "'" for v in values) + ')'


HEADER = ('-- Generated by scripts/gen_m365_usage_sql.py - edit the generator, not this file.\n'
          '-- Runs on the Lakehouse SQL endpoint from the M365 Usage Analytics template ({name}).\n')

# Shared row-level base: one row per rollup row with normalised keys and app flags.
BASE = f"""r AS (
    SELECT
        LOWER(COALESCE(UserId, '')) AS uid,
        COALESCE(UserId, '') AS UserId,
        COALESCE(LEFT(CreationDate, 10), '') AS dk,
        COALESCE(Operation, '') AS op,
        COALESCE(Workload, '') AS wl,
        LOWER(COALESCE(SourceFileExtension, '')) AS ext,
        LOWER(COALESCE(AppHost, '')) AS host,
        CAST(COALESCE(EventCount, 1) AS BIGINT) AS ec
    FROM dbo.m365_usage_rollup
),
nm AS (
    SELECT uid, MIN(UserId) AS UserId FROM r GROUP BY uid
)"""

APP_CASE = f"""CASE
            WHEN ext IN {_in(WORD_EXTS)} AND op IN {_in(FILE_OPS)} THEN 'Word'
            WHEN ext IN {_in(EXCEL_EXTS)} AND op IN {_in(FILE_OPS)} THEN 'Excel'
            WHEN ext IN {_in(PPT_EXTS)} AND op IN {_in(FILE_OPS)} THEN 'PowerPoint'
            WHEN wl = 'Exchange' AND op IN {_in(OUTLOOK_OPS)} THEN 'Outlook'
            WHEN wl = 'MicrosoftTeams' AND op IN {_in(TEAMS_OPS)} THEN 'Teams'
            WHEN wl = 'Copilot' OR op = 'CopilotInteraction' THEN 'Copilot'
            ELSE 'M365 All Apps'
        END"""


def _seg(days):
    rate = f'CAST({days} AS FLOAT) * CAST(7 AS FLOAT) / CAST(b.wdays AS FLOAT)'
    return (f"CASE WHEN {days} <= 0 OR b.wdays <= 0 THEN '0. No Usage'"
            f" WHEN {rate} < CAST(1 AS FLOAT) THEN '1. <1 Day/Week (Light)'"
            f" WHEN {rate} < CAST(3 AS FLOAT) THEN '2. 1-2 Days/Week (Moderate)'"
            f" WHEN {rate} < CAST(5 AS FLOAT) THEN '3. 3-4 Days/Week (Frequent)'"
            f" ELSE '4. 5+ Days/Week (Daily)' END")


def _tier(col, m, zero_is_bottom):
    zero = f"WHEN {col} = 0 THEN 'Bottom 50%' " if zero_is_bottom else ''
    return (f"CASE {zero}WHEN {col} >= th.{m}90 THEN 'Top 10%' WHEN {col} >= th.{m}75 THEN '10-25%'"
            f" WHEN {col} >= th.{m}50 THEN '25-50%' ELSE 'Bottom 50%' END")


def _priority(m, c):
    top2 = "('Top 10%', '10-25%')"
    return (f"CASE WHEN {m} IN {top2} AND {c} IN {top2} THEN 'Promoter'"
            f" WHEN {m} = 'Top 10%' AND {c} = '25-50%' THEN 'High'"
            f" WHEN {m} = 'Top 10%' AND {c} = 'Bottom 50%' THEN 'Critical'"
            f" WHEN {m} = '10-25%' AND {c} = '25-50%' THEN 'Medium'"
            f" WHEN {m} = '10-25%' AND {c} = 'Bottom 50%' THEN 'High'"
            f" WHEN {m} IN ('25-50%', 'Bottom 50%') AND {c} IN {top2} THEN 'Promoter'"
            f" WHEN {m} = '25-50%' AND {c} IN ('25-50%', 'Bottom 50%') THEN 'Medium'"
            f" ELSE 'Low' END")


def userstats():
    raw_flags = {
        'Teams': f"wl = 'MicrosoftTeams' AND op IN {_in(DAX_TEAMS_OPS)}",
        'Outlook': f"wl = 'Exchange' AND op IN {_in(DAX_OUTLOOK_OPS)}",
        'Word': f"op IN {_in(DAX_FILE_OPS)} AND ext IN {_in(WORD_EXTS)}",
        'Excel': f"op IN {_in(DAX_FILE_OPS)} AND ext IN {_in(EXCEL_EXTS)}",
        'PowerPoint': f"op IN {_in(DAX_FILE_OPS)} AND ext IN {_in(PPT_EXTS)}",
        'CopilotChat': "op = 'CopilotInteraction'",
    }
    win_cond = {'L30': 'f.in30 = 1 AND ', 'L60': 'f.in60 = 1 AND ', 'Full': ''}
    raw_sums = ',\n        '.join(
        f'SUM(CASE WHEN {win_cond[w]}f.raw_{a} = 1 THEN f.ec ELSE 0 END) AS {a}Raw_{w}'
        for a in RAW_APPS for w in WINDOWS)
    raw_flag_cols = ',\n        '.join(
        f'CASE WHEN {cond} THEN 1 ELSE 0 END AS raw_{a}' for a, cond in raw_flags.items())

    rank_src = []
    for a in RANK_APPS:
        for w in WINDOWS:
            v = (' + '.join(f'{x}Raw_{w}' for x in RAW_APPS[:5]) if a == 'M365AllApps' else f'{a}Raw_{w}')
            rank_src.append(f"SELECT uid, 'CERank_{a}_{w}' AS k, {v} AS v FROM u")
    for w in WINDOWS:
        rank_src.append(f"SELECT u.uid, 'CECopilotPercentile_{w}' AS k, sp.p_{w} AS v"
                        f" FROM u JOIN sp ON sp.uid = u.uid")
    rank_union = '\n    UNION ALL '.join(rank_src)
    rank_keys = [f'CERank_{a}_{w}' for a in RANK_APPS for w in WINDOWS] + \
                [f'CECopilotPercentile_{w}' for w in WINDOWS]
    rank_pivot = ',\n        '.join(f"MAX(CASE WHEN k = '{k}' THEN r END) AS {k}" for k in rank_keys)
    pct_metrics = ['cop', 'm365', 'excop', 'exm365']
    th_cols = ',\n        '.join(f"MAX(CASE WHEN m = '{m}' AND pk = {p} THEN val END) AS {m}{p}"
                                for m in pct_metrics for p in (90, 75, 50))

    seg_cols = ',\n    '.join(f'{_seg(d)} AS {name}' for d, name in [
        ('u.td', 'TeamsActivitySegment'), ('u.od', 'OutlookActivitySegment'), ('u.wd', 'WordActivitySegment'),
        ('u.xd', 'ExcelActivitySegment'), ('u.pd', 'PowerPointActivitySegment'),
        ('(u.wd + u.xd + u.pd)', 'OfficeFilesActivitySegment'), ('u.alld', 'OverallM365ActivitySegment')])
    raw_out = ',\n    '.join(f'u.{a}Raw_{w}' for a in RAW_APPS for w in WINDOWS)
    rank_out = ',\n    '.join(f'ce.{k}' for k in rank_keys)

    return HEADER.format(name='m365_usage_userstats') + f"""WITH
{BASE},
bounds AS (
    SELECT MIN(CASE WHEN dk <> '' THEN dk END) AS mind, MAX(CASE WHEN dk <> '' THEN dk END) AS maxd FROM r
),
b AS (
    SELECT
        CASE WHEN maxd IS NULL THEN 1
             ELSE DATEDIFF(day, CAST(mind AS DATE), CAST(maxd AS DATE)) + 1 END AS wdays,
        CASE WHEN maxd IS NULL THEN '9999-12-31'
             ELSE CAST(DATEADD(day, -29, CAST(maxd AS DATE)) AS VARCHAR(10)) END AS c30,
        CASE WHEN maxd IS NULL THEN '9999-12-31'
             ELSE CAST(DATEADD(day, -59, CAST(maxd AS DATE)) AS VARCHAR(10)) END AS c60
    FROM bounds
),
f AS (
    SELECT r.uid, r.dk, r.op, r.wl, r.ext, r.host, r.ec,
        CASE WHEN r.wl = 'Copilot' OR r.op IN {_in(COPILOT_OPS)} THEN 1 ELSE 0 END AS is_cop,
        CASE WHEN r.wl = 'MicrosoftTeams' AND r.op IN {_in(TEAMS_OPS)} THEN 1 ELSE 0 END AS t_f,
        CASE WHEN r.wl = 'Exchange' AND r.op IN {_in(OUTLOOK_OPS)} THEN 1 ELSE 0 END AS o_f,
        CASE WHEN r.ext IN {_in(WORD_EXTS)} AND r.op IN {_in(FILE_OPS)} THEN 1 ELSE 0 END AS w_f,
        CASE WHEN r.ext IN {_in(EXCEL_EXTS)} AND r.op IN {_in(FILE_OPS)} THEN 1 ELSE 0 END AS x_f,
        CASE WHEN r.ext IN {_in(PPT_EXTS)} AND r.op IN {_in(FILE_OPS)} THEN 1 ELSE 0 END AS p_f,
        {raw_flag_cols},
        CASE WHEN r.dk <> '' AND r.dk >= b.c30 THEN 1 ELSE 0 END AS in30,
        CASE WHEN r.dk <> '' AND r.dk >= b.c60 THEN 1 ELSE 0 END AS in60
    FROM r CROSS JOIN b
),
u AS (
    SELECT f.uid,
        SUM(CASE WHEN f.is_cop = 1 THEN f.ec ELSE 0 END) AS cop,
        SUM(CASE WHEN f.is_cop = 0 THEN f.ec ELSE 0 END) AS m365,
        SUM(CASE WHEN f.is_cop = 1 AND f.host = 'excel' THEN 1 ELSE 0 END) AS excop,
        SUM(CASE WHEN f.is_cop = 0 AND f.x_f = 1 THEN 1 ELSE 0 END) AS exm365,
        COUNT(DISTINCT CASE WHEN f.t_f = 1 THEN f.dk END) AS td,
        COUNT(DISTINCT CASE WHEN f.o_f = 1 THEN f.dk END) AS od,
        COUNT(DISTINCT CASE WHEN f.w_f = 1 THEN f.dk END) AS wd,
        COUNT(DISTINCT CASE WHEN f.x_f = 1 THEN f.dk END) AS xd,
        COUNT(DISTINCT CASE WHEN f.p_f = 1 THEN f.dk END) AS pd,
        COUNT(DISTINCT CASE WHEN f.t_f = 1 OR f.o_f = 1 OR f.w_f = 1 OR f.x_f = 1 OR f.p_f = 1 THEN f.dk END) AS alld,
        SUM(CASE WHEN f.t_f = 1 THEN f.ec ELSE 0 END) AS tact,
        SUM(CASE WHEN f.o_f = 1 THEN f.ec ELSE 0 END) AS oact,
        SUM(CASE WHEN f.w_f = 1 OR f.x_f = 1 OR f.p_f = 1 THEN f.ec ELSE 0 END) AS offact,
        {raw_sums}
    FROM f
    GROUP BY f.uid
),
-- Inclusive linear-interpolation percentiles (PERCENTILE_CONT semantics) over all users, zeros included.
pv AS (
    SELECT 'cop' AS m, CAST(cop AS FLOAT) AS v FROM u
    UNION ALL SELECT 'm365', CAST(m365 AS FLOAT) FROM u
    UNION ALL SELECT 'excop', CAST(excop AS FLOAT) FROM u
    UNION ALL SELECT 'exm365', CAST(exm365 AS FLOAT) FROM u
),
pr AS (
    SELECT m, v, ROW_NUMBER() OVER (PARTITION BY m ORDER BY v) - 1 AS i FROM pv
),
ps AS (
    SELECT 90 AS pk, CAST(0.9 AS FLOAT) AS p
    UNION ALL SELECT 75, CAST(0.75 AS FLOAT)
    UNION ALL SELECT 50, CAST(0.5 AS FLOAT)
),
pn AS (
    SELECT ps.pk, ps.p * CAST(c.n - 1 AS FLOAT) AS idx, c.n
    FROM ps CROSS JOIN (SELECT COUNT(*) AS n FROM u) c
),
pix AS (
    SELECT pk, idx, FLOOR(idx) AS lo,
        CASE WHEN FLOOR(idx) + 1 > n - 1 THEN CAST(n - 1 AS FLOAT) ELSE FLOOR(idx) + 1 END AS hi
    FROM pn
),
pct AS (
    SELECT pr.m, pix.pk,
        MAX(CASE WHEN pr.i = pix.lo THEN pr.v END)
          + (MAX(pix.idx) - MAX(pix.lo))
          * (MAX(CASE WHEN pr.i = pix.hi THEN pr.v END) - MAX(CASE WHEN pr.i = pix.lo THEN pr.v END)) AS val
    FROM pr CROSS JOIN pix
    GROUP BY pr.m, pix.pk
),
th AS (
    SELECT
        {th_cols}
    FROM pct
),
rk AS (
    SELECT uid,
        CASE WHEN cop > 0 THEN ROW_NUMBER() OVER (
            PARTITION BY CASE WHEN cop > 0 THEN 1 ELSE 0 END ORDER BY cop, uid) - 1 END AS cop_rn,
        SUM(CASE WHEN cop > 0 THEN 1 ELSE 0 END) OVER () AS cop_n,
        ROW_NUMBER() OVER (ORDER BY m365, uid) - 1 AS m_rn,
        COUNT(*) OVER () AS tot
    FROM u
),
-- Copilot prompts per user and window, for CECopilotPercentile.
sp AS (
    SELECT s.uid,
        SUM(CASE WHEN s.dk >= b.c30 THEN s.pc ELSE 0 END) AS p_L30,
        SUM(CASE WHEN s.dk >= b.c60 THEN s.pc ELSE 0 END) AS p_L60,
        SUM(s.pc) AS p_Full
    FROM (
        SELECT LOWER(TRIM(COALESCE(UserId, ''))) AS uid,
            COALESCE(LEFT(CreationDate, 10), '') AS dk,
            CAST(COALESCE(PromptCount, 0) AS BIGINT) AS pc
        FROM dbo.m365_usage_sessionstats
    ) s CROSS JOIN b
    WHERE s.pc > 0 AND s.uid <> ''
    GROUP BY s.uid
),
-- Integer percentile rank: share of positive scorers at or below this score, rounded half-to-even.
ce_in AS (
    {rank_union}
),
ce_pos AS (
    SELECT uid, k,
        CAST(COUNT(*) OVER (PARTITION BY k) - RANK() OVER (PARTITION BY k ORDER BY v DESC) + 1 AS FLOAT)
          / CAST(COUNT(*) OVER (PARTITION BY k) AS FLOAT) * CAST(100 AS FLOAT) AS x
    FROM ce_in
    WHERE v > 0
),
ce_r AS (
    SELECT uid, k,
        CAST(CASE WHEN x - FLOOR(x) > CAST(0.5 AS FLOAT) THEN FLOOR(x) + 1
                  WHEN x - FLOOR(x) < CAST(0.5 AS FLOAT) THEN FLOOR(x)
                  WHEN CAST(FLOOR(x) AS BIGINT) % 2 = 0 THEN FLOOR(x)
                  ELSE FLOOR(x) + 1 END AS BIGINT) AS r
    FROM ce_pos
),
ce AS (
    SELECT uid,
        {rank_pivot}
    FROM ce_r
    GROUP BY uid
),
t AS (
    SELECT u.uid,
        {_tier('u.cop', 'cop', True)} AS cop_tier,
        {_tier('u.m365', 'm365', False)} AS m365_tier,
        {_tier('u.excop', 'excop', False)} AS excop_tier,
        {_tier('u.exm365', 'exm365', False)} AS exm365_tier
    FROM u CROSS JOIN th
)
SELECT
    nm.UserId,
    u.cop AS CopilotEC,
    u.m365 AS M365EC,
    u.excop AS ExCopEC,
    u.exm365 AS ExM365EC,
    CASE WHEN u.cop > 0 THEN 'Copilot User' ELSE 'Non-Copilot User' END AS IsCopilotUser,
    t.cop_tier AS CopilotTierColumn,
    t.m365_tier AS M365TierColumn,
    {_priority('t.m365_tier', 't.cop_tier')} AS PriorityScatterColumn,
    {_priority('t.exm365_tier', 't.excop_tier')} AS ExcelPriority,
    CAST(ROUND(CASE WHEN u.cop > 0 THEN CAST(rk.cop_rn AS FLOAT) / CAST(rk.cop_n AS FLOAT)
                    ELSE CAST(0 AS FLOAT) END, 6) AS DECIMAL(9, 6)) AS CopilotUsageRankColumn,
    CAST(ROUND(CAST(rk.m_rn AS FLOAT) / CAST(rk.tot AS FLOAT), 6) AS DECIMAL(9, 6)) AS M365UsageRankColumn,
    u.td AS TeamsActiveDays,
    u.od AS OutlookActiveDays,
    u.wd AS WordActiveDays,
    u.xd AS ExcelActiveDays,
    u.pd AS PowerPointActiveDays,
    u.tact AS TeamsActivityCount,
    u.oact AS OutlookActivityCount,
    u.offact AS OfficeFilesActivityCount,
    {seg_cols},
    {raw_out},
    {rank_out}
FROM u
JOIN nm ON nm.uid = u.uid
JOIN t ON t.uid = u.uid
JOIN rk ON rk.uid = u.uid
CROSS JOIN b
LEFT JOIN ce ON ce.uid = u.uid
"""


def sessioncohort():
    return HEADER.format(name='m365_usage_sessioncohort') + f"""WITH
{BASE},
a AS (
    SELECT uid, dk,
        {APP_CASE} AS app
    FROM r
),
s AS (
    SELECT uid, app, COUNT(DISTINCT dk) AS n FROM a WHERE app <> 'M365 All Apps' GROUP BY uid, app
)
SELECT
    nm.UserId,
    s.app AS AppColumn,
    CASE WHEN s.n <= 5 THEN '1-5 sessions'
         WHEN s.n <= 10 THEN '6-10 sessions'
         WHEN s.n <= 20 THEN '11-20 sessions'
         WHEN s.n <= 40 THEN '21-40 sessions'
         WHEN s.n <= 60 THEN '41-60 sessions'
         WHEN s.n <= 80 THEN '61-80 sessions'
         ELSE '81+ sessions' END AS SessionCohort
FROM s
JOIN nm ON nm.uid = s.uid
"""


def entrausers():
    return HEADER.format(name='m365_usage_entrausers') + f"""-- Built from the org-data and licensed-users tables the lake already ingests, so the template needs
-- no Graph call. The template adds its other expected columns as blanks and derives hasLicense
-- from assignedLicenses.
SELECT
    o.PersonId AS userPrincipalName,
    o.displayName,
    o.PersonId AS mail,
    o.JobTitle AS jobTitle,
    o.Organization AS department,
    o.companyName,
    o.officeLocation,
    o.city,
    o.country,
    o.accountEnabled,
    o.managerUPN AS manager_userPrincipalName,
    CASE WHEN UPPER(COALESCE(l.Has_license, '')) = 'TRUE'
         THEN '[{{"skuId":"{COPILOT_SKU}"}}]' ELSE '[]' END AS assignedLicenses,
    CASE WHEN UPPER(COALESCE(l.Has_license, '')) = 'TRUE' THEN 'True' ELSE 'False' END AS hasLicense
FROM dbo.copilot_org_data o
LEFT JOIN dbo.copilot_licensed_users l ON l.UPN_Normalized = o.PersonId_Normalized
WHERE COALESCE(o.PersonId, '') <> ''
"""


QUERIES = {'userstats': userstats, 'sessioncohort': sessioncohort, 'entrausers': entrausers}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in QUERIES.items():
        (OUT / f'{name}.sql').write_text(fn(), encoding='utf-8', newline='\n')
        print(f'wrote {OUT / (name + ".sql")}')


if __name__ == '__main__':
    main()
